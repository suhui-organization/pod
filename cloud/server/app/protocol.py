# 端 A（本机）↔ 端 B（云端控制平面）的协议契约（服务端一侧）。
#
# 对照实现：apps/cli/src/protocol.ts；完整说明见 docs/local-cloud-contract.md。
#
# 为什么需要它：两端分开发布——客户端按 tag 发（用户装完不动），服务端按镜像滚。
# 版本错配必然发生，而"错配"在这类系统里的表现往往不是报错，是**静默半失效**：
# 老客户端不认新端点（只打一行警告）、新字段没人读。所以服务端要能回答两个问题：
# ① 这台机器装的是哪一版？② 它是不是已经旧到少了一半能力？——并在响应里直说。

# 服务端协议版本。只在**破坏性变更**（改字段含义 / 删字段 / 改语义）时 +1。
SERVER_PROTOCOL = 1

# 服务端能接受的最低客户端协议。低于它 → 响应里 client_outdated=true + 说明，
# 但**不拒绝请求**：可用性优先，能力差异要让用户看见，而不是让同步失败。
MIN_CLIENT_PROTOCOL = 1
